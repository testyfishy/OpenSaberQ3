<#
.SYNOPSIS
  Add the Meta device declaration to the Godot Android build template.

.DESCRIPTION
  Without `com.oculus.supportedDevices` in AndroidManifest.xml the Horizon runtime puts the
  app into compatibility mode and treats the headset as a previous-generation device. The
  visible symptom is that OpenXR reports only 72 Hz as available, so 90 Hz and 120 Hz requests
  are silently refused - it looks like a hardware limitation but is a manifest declaration.

  `android/build` is generated by Godot's "install Android build template" and is gitignored,
  so this must be re-applied after a fresh template install. Run it once per clone:

      pwsh -File tools/build/patch-android-manifest.ps1

  Idempotent: running it twice changes nothing.

.NOTES
  Requires android/build to exist (install the Android build template first).
#>
[CmdletBinding()]
param(
    [string]$Manifest = 'android/build/src/main/AndroidManifest.xml'
)

$ErrorActionPreference = 'Stop'
if (-not (Test-Path $Manifest)) { throw "manifest not found: $Manifest (install the Android build template first)" }

$content = Get-Content $Manifest -Raw
$meta = @(
    '        <meta-data android:name="com.oculus.supportedDevices" android:value="quest2|questpro|quest3|quest3s" />',
    '        <meta-data android:name="com.oculus.intent.category.VR" android:value="vr_only" />'
)

if ($content -match 'com\.oculus\.supportedDevices') {
    Write-Host "already declared - nothing to do"
    exit 0
}

# The application element spans several lines; its attributes end on the line whose last
# non-space character is '>'. Insert after that, never between '<application' and its attributes.
$lines = [System.Collections.Generic.List[string]](Get-Content $Manifest)
$appIdx = -1
for ($i = 0; $i -lt $lines.Count; $i++) { if ($lines[$i] -match '^\s*<application\b') { $appIdx = $i; break } }
if ($appIdx -lt 0) { throw "no <application> element found in $Manifest" }

$openEnd = -1
for ($i = $appIdx; $i -lt $lines.Count; $i++) {
    if ($lines[$i].TrimEnd().EndsWith('>')) { $openEnd = $i; break }
}
if ($openEnd -lt 0) { throw "could not find the end of the <application> open tag" }

for ($k = $meta.Count - 1; $k -ge 0; $k--) { $lines.Insert($openEnd + 1, $meta[$k]) }
Set-Content -Path $Manifest -Value $lines -Encoding utf8

# Verify it really landed inside <application>
$check = Get-Content $Manifest -Raw
$appBlock = [regex]::Match($check, '(?s)<application\b.*?</application>').Value
if ($appBlock -notmatch 'com\.oculus\.supportedDevices') { throw "patch verification failed: meta-data is not inside <application>" }
Write-Host "patched $Manifest"
